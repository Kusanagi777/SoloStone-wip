using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using SabberStoneCore.CardSets.DungeonRun;

/// <summary>
/// Plugin host for the Dungeon Run mode: embedded data, load-time validation against the client, the active
/// profile's sidecar save (upgraded from version 1 on load), the in-match name/text overrides, and the start-a-run API
/// (<see cref="Classes"/>, <see cref="DecksFor"/>, <see cref="PowersFor"/>, <see cref="NewRun"/>) that the plank menu and the
/// native Adventure picker share. Match staging and the run screens build on it.
/// </summary>
internal static class DungeonRunRuntime
{
    internal const string RunResource = "SoloStone.DungeonRun.run-v1.json";
    internal const string PoolResource = "SoloStone.DungeonRun.pool-v1.json";
    internal const string CatalogResource = "SoloStone.DungeonRun.catalog-v1.json";
    internal const string ScheduleResource = "SoloStone.DungeonRun.schedule-v1.json";
    internal const string TavernResource = "SoloStone.DungeonRun.tavern-v1.json";
    /// <summary>Phase 8: the imported adventure encounters (generated by tools/dungeon-run-catalog, step encounters).</summary>
    internal const string EncountersResource = "SoloStone.DungeonRun.encounters-v1.json";

    private static List<string> catalogDiagnostics = new List<string>();
    /// <summary>
    /// What the load changed in the draft catalog, one line each ("catalog: &lt;entry&gt; dropped &lt;id&gt; client-unknown"):
    /// candidates this client does not know and entries withdrawn for it. Logged and counted on the class page.
    /// </summary>
    internal static IReadOnlyList<string> CatalogDiagnostics { get { EnsureLoaded(); return catalogDiagnostics; } }

    private static readonly object Gate = new object();
    private static DungeonRun rules;
    private static List<string> disabledReasons;
    private static string loadedDirectory;
    private static DungeonRunSave save;
    // The loaded save has been upgraded, refreshed and resumed under the current rules (they can load after the save does).
    private static bool savePrepared;
    // Names shown during the current run match, by card id (shells, the player's hero, the boss's hero).
    private static Dictionary<string, string> matchNames;

    /// <summary>The loaded rules, or null when the mode is disabled (see <see cref="DisabledReasons"/>).</summary>
    internal static DungeonRun Rules { get { EnsureLoaded(); return rules; } }

    internal static bool Available => Rules != null;

    /// <summary>Why the mode is disabled: one line per failed check (design R6, AC7). Empty when available.</summary>
    internal static IReadOnlyList<string> DisabledReasons { get { EnsureLoaded(); return disabledReasons ?? NotReady; } }

    internal static Action<string> Log;

    private static readonly List<string> NotReady = new List<string> { "the client has not finished loading" };

    private static void EnsureLoaded()
    {
        lock (Gate)
        {
            if (disabledReasons != null) return;
            // Validation asks the client for entity definitions; before the bridge is ready every answer is "no",
            // which would disable the mode for the whole session. Report not-ready without caching it.
            if (!ClientBridge.Ready) { rules = null; return; }
            try
            {
                NpcWorldJson.Parser = EmbeddedJson.Parse;
                // With the act/floor schedules loaded, a new run follows schedule-v1.json "default"; runs of older saves keep the
                // legacy eight floors (ScheduleVersion 0).
                var data = DungeonRunData.Parse(Read(RunResource), Read(PoolResource), Read(NpcDeckLibrary.ResourceName), Read(CatalogResource),
                    Read(ScheduleResource), Read(TavernResource), Read(EncountersResource));
                // Matches send engine ids through NativeMatch.TransportCardId (e.g. CS2_017 -> HERO_06bp, the 37.x basic
                // powers), so check the id the client will actually be sent.
                Func<string, bool> clientKnows = id => ClientBridge.ClientKnowsCard(NativeMatch.TransportCardId(id));
                // The catalog tool cannot see the client's card table: drop the pool candidates this client lacks (logged and
                // counted), then validate. Any other catalog failure is a validation error (the catalog is stale).
                catalogDiagnostics = DungeonRunValidator.DropClientUnknown(data, clientKnows);
                foreach (string line in catalogDiagnostics) Log?.Invoke("Dungeon Run " + line);
                var errors = DungeonRunValidator.Validate(data, clientKnows);
                disabledReasons = errors;
                rules = errors.Count == 0 ? new DungeonRun(data) : null;
            }
            catch (Exception failure)
            {
                disabledReasons = new List<string> { "data failed to load: " + failure.GetType().Name + ": " + failure.Message };
                rules = null;
            }
            // Step 9 (lane R, D17): BuildPlan logs a forbidden pair the run holds; it never changes the plan.
            DungeonRun.ForbiddenPairLog = line => Log?.Invoke("Dungeon Run forbidden pair, " + line);
            foreach (string reason in disabledReasons.Take(20)) Log?.Invoke("Dungeon Run disabled: " + reason);
            if (disabledReasons.Count > 20) Log?.Invoke("Dungeon Run disabled: ...and " + (disabledReasons.Count - 20) + " more");
            if (rules != null) Log?.Invoke("Dungeon Run ready: " + rules.Data.Classes.Count + " classes, " + rules.Data.Decks.Count + " decks, "
                + rules.Data.Bosses.Count + " bosses, " + rules.Data.Treasures.Count + " treasures, catalog v" + rules.Data.CatalogVersion + " "
                + rules.Data.Bundles.Count(b => b.Offerable) + " offerable entries (" + catalogDiagnostics.Count + " load notes), schedule v"
                + (rules.Data.Schedules?.ScheduleVersion ?? 0) + " default " + (rules.Data.Schedules?.Default ?? "legacy") + ", tavern v"
                + (rules.Data.Tavern?.TavernVersion ?? 0) + " " + (rules.Data.Tavern?.Options.Count(o => o.Weight > 0) ?? 0) + " options (" + rules.Data.DataVersion + ")");
        }
    }

    private static string Read(string resourceName)
    {
        using (Stream stream = Assembly.GetExecutingAssembly().GetManifestResourceStream(resourceName)
            ?? throw new InvalidDataException("Missing embedded resource: " + resourceName))
        using (var reader = new StreamReader(stream))
            return reader.ReadToEnd();
    }

    // ------------------------------------------------------------------ save (design R11)

    /// <summary>
    /// The active profile's Dungeon Run save. Once the rules are loaded it is upgraded from version 1 (in memory; the next
    /// commit writes it, after a one-time copy of the old file), its unlocks are refreshed from its stats, and a run left
    /// mid-match resumes at its pre-match. A file of a newer version throws and is never overwritten.
    /// </summary>
    internal static DungeonRunSave Save
    {
        get
        {
            lock (Gate)
            {
                string directory = LocalLadder.Profile?.DirectoryPath;
                if (directory == null) return null;
                if (save == null || directory != loadedDirectory)
                {
                    save = null;
                    var loaded = DungeonRunStore.Load(directory);
                    save = loaded; loadedDirectory = directory; savePrepared = false;
                }
                var run = Rules;
                if (run != null && !savePrepared)
                {
                    savePrepared = true;
                    try
                    {
                        DungeonRunMigration.Upgrade(save, run, Log);
                        run.RefreshUnlocks(save.Profile);
                        if (save.Active != null && save.Active.Class != null) run.Resume(save.Active);
                    }
                    catch (Exception failure) { Log?.Invoke("Dungeon Run save preparation failed: " + failure.GetType().Name + ": " + failure.Message); }
                }
                return save;
            }
        }
    }

    /// <summary>Writes the active profile's save. Called after every phase change (new run, outcome, pick).</summary>
    internal static void Commit()
    {
        lock (Gate)
        {
            if (save == null || loadedDirectory == null) return;
            DungeonRunStore.Save(loadedDirectory, save);
        }
    }

    /// <summary>
    /// Applies a change to the cached save and commits it. If anything throws (the commit included), the cached run and
    /// profile go back to their copy from before the change, so memory never holds a change the sidecar does not.
    /// </summary>
    internal static void Mutate(Action<DungeonRunSave> mutation)
    {
        lock (Gate)
        {
            var loaded = Save ?? throw new InvalidOperationException(NativeDungeonRunText.NoSaveCaption);
            var snapshot = DungeonRunStore.Clone(loaded);
            try { mutation(loaded); Commit(); }
            catch
            {
                DungeonRunStore.Restore(loaded, snapshot);
                throw;
            }
        }
    }

    /// <summary>Re-applies the unlock conditions to the loaded profile, in memory (the next commit writes them).</summary>
    internal static void RefreshUnlocks()
    {
        lock (Gate)
        {
            var run = Rules;
            DungeonRunSave loaded;
            try { loaded = Save; } catch (Exception) { return; }
            if (run != null && loaded != null) run.RefreshUnlocks(loaded.Profile);
        }
    }

    // ------------------------------------------------------------------ start-a-run API (plank menu and native picker)

    /// <summary>The selectable classes; empty when the mode is unavailable or no save is loaded.</summary>
    internal static IReadOnlyList<RunClassOption> Classes
    {
        get { lock (Gate) return Catalog(profile => DungeonRunCatalog.Classes(rules, profile, ClientCardId), new RunClassOption[0]); }
    }

    /// <summary>
    /// The rows a run can start on under a class (phase 6, the Hero step): the class row, then its named hero rows; empty for
    /// an unknown class.
    /// </summary>
    internal static IReadOnlyList<RunHeroOption> HeroesFor(string classId)
    {
        lock (Gate) return Catalog(profile => DungeonRunCatalog.Heroes(rules, profile, classId, ClientCardId), new RunHeroOption[0]);
    }

    // The seed the next NewRun uses once a signature offer was shown for it (the offer is drawn from the run seed, so the
    // picker must see it before the run starts); dropped when another row is chosen.
    private static long? pendingSeed;
    private static string pendingSeedRow;

    /// <summary>
    /// The signature treasures the next run of <paramref name="rowId"/> is offered (phase 6, Tombs of Terror); empty for a row
    /// with none. Rolls the run seed now and keeps it for <see cref="NewRun"/>, so the offer shown is the offer checked.
    /// </summary>
    internal static IReadOnlyList<RunSignatureOption> SignaturesFor(string rowId)
    {
        lock (Gate)
        {
            if (pendingSeedRow != rowId || pendingSeed == null) { pendingSeed = RandomSeed(); pendingSeedRow = rowId; }
            long seed = pendingSeed.Value;
            return Catalog(profile => DungeonRunCatalog.Signatures(rules, profile, rowId, seed), new RunSignatureOption[0]);
        }
    }

    /// <summary>The class's three starter decks with unlock state and hint; empty for an unknown class.</summary>
    internal static IReadOnlyList<RunDeckOption> DecksFor(string classId)
    {
        lock (Gate) return Catalog(profile => DungeonRunCatalog.Decks(rules, profile, classId), new RunDeckOption[0]);
    }

    /// <summary>The class's three hero powers with unlock state and hint; empty for an unknown class.</summary>
    internal static IReadOnlyList<RunPowerOption> PowersFor(string classId)
    {
        lock (Gate) return Catalog(profile => DungeonRunCatalog.Powers(rules, profile, classId, ClientCardId), new RunPowerOption[0]);
    }

    /// <summary>
    /// Build Deck: the cards a starter of row <paramref name="rowId"/> may hold, from the active profile's collection, by cost
    /// then name. Every collectible engine card the row admits (<see cref="DungeonRunBuild.CardReason"/> null) whose client id
    /// (<see cref="ClientCardId"/>) the player owns, with its owned count (golden and normal) and copy group. Empty for an
    /// unknown row, with no profile open, or when the mode is unavailable.
    /// </summary>
    internal static IReadOnlyList<RunBuildCard> BuildCandidates(string rowId)
    {
        var empty = new RunBuildCard[0];
        try
        {
            var run = Rules;
            var cls = run?.Data.FindClass(rowId);
            var collection = LocalLadder.Profile;
            if (cls == null || collection == null) return empty;
            // LocalProfile.TotalOwnedCount sums OwnedCards per id; summed once here instead of once per engine card.
            var owned = collection.OwnedCards.Where(c => c.Id != null).GroupBy(c => c.Id, StringComparer.Ordinal)
                .ToDictionary(g => g.Key, g => g.Sum(c => c.Count), StringComparer.Ordinal);
            var policy = SabberStoneCore.Model.OfflinePoolPolicy.Load();
            var result = new List<RunBuildCard>();
            foreach (var card in SabberStoneCore.Model.Cards.All)
            {
                if (card?.Id == null || !card.Collectible) continue;
                string clientId = ClientCardId(card.Id);
                if (!owned.TryGetValue(clientId, out int count) || count <= 0) continue;
                if (DungeonRunBuild.CardReason(card.Id, cls.ClassSet, policy) != null) continue;
                result.Add(new RunBuildCard
                {
                    Id = card.Id, ClientId = clientId, Name = card.Name, Cost = card.Cost,
                    Legendary = card.Rarity == SabberStoneCore.Enums.Rarity.LEGENDARY, Owned = count,
                    CopyGroup = LocalCardCatalog.CopyGroup(clientId),
                });
            }
            return result.OrderBy(c => c.Cost).ThenBy(c => c.Name, StringComparer.Ordinal).ThenBy(c => c.Id, StringComparer.Ordinal).ToList();
        }
        catch (Exception failure) { Log?.Invoke("Dungeon Run build candidates failed: " + failure.GetType().Name + ": " + failure.Message); return empty; }
    }

    private static IReadOnlyList<T> Catalog<T>(Func<DungeonRunProfile, IReadOnlyList<T>> read, IReadOnlyList<T> empty)
    {
        try
        {
            if (Rules == null) return empty;
            var loaded = Save;
            return loaded == null ? empty : read(loaded.Profile);
        }
        catch (Exception failure) { Log?.Invoke("Dungeon Run catalog failed: " + failure.GetType().Name + ": " + failure.Message); return empty; }
    }

    /// <summary>The card id the client is sent for an engine id (e.g. a 37.x basic power), as in a run match.</summary>
    internal static string ClientCardId(string engineId) => engineId == null ? null : NativeMatch.TransportCardId(engineId);

    /// <summary>
    /// Starts and commits a run with a random seed. Returns null on success, else the refusal shown to the player
    /// ("That deck is locked.", ...). A finished run still on the save (its summary not dismissed) is replaced: it is
    /// already in the archive. Nothing is written on a refusal.
    /// </summary>
    /// <param name="signatureId">A hero row with signatures (phase 6): one of <see cref="SignaturesFor"/>; else null.</param>
    /// <param name="builtCards">Build Deck: the engine card ids the player built (<paramref name="deckId"/> the row's build deck),
    /// else null. Re-checked first with <see cref="DungeonRunBuild.DeckReasons"/> against the active profile's owned counts and
    /// copy groups (the run's own check groups copies by id and skips ownership); the reasons are the refusal.</param>
    internal static string NewRun(string classId, string deckId, string powerId, string signatureId = null, IReadOnlyList<string> builtCards = null)
    {
        var run = Rules;
        if (run == null) return "Dungeon Run is unavailable.";
        DungeonRunState state = null;
        try
        {
            var loaded = Save;
            if (loaded == null) return NativeDungeonRunText.NoSaveCaption;
            if (loaded.Active != null && !loaded.Active.Finished) return "A run is already in progress.";
            if (builtCards != null)
            {
                string builtRefusal = BuiltListRefusal(run, classId, builtCards);
                if (builtRefusal != null) return builtRefusal;
            }
            long seed;
            lock (Gate) seed = pendingSeedRow == classId && pendingSeed != null ? pendingSeed.Value : RandomSeed();
            Mutate(s => { state = run.NewRun(s.Profile, classId, deckId, powerId, seed, signatureId: signatureId, builtCards: builtCards); s.Active = state; });
            lock (Gate) { pendingSeed = null; pendingSeedRow = null; }
        }
        catch (ArgumentException refusal) { return refusal.Message; }
        catch (InvalidOperationException refusal) { return refusal.Message; }
        catch (Exception failure) { return NativeDungeonRunText.Failed(failure.Message); }
        Log?.Invoke("DUNGEON_RUN new run class=" + state.Class + " deck=" + state.StarterDeck + (state.BuiltDeck ? " built=true" : "") + " power=" + state.Power + " seed=" + state.SeedText
            + (state.IsActRun ? " schedule=" + state.Schedule + " v" + state.ScheduleVersion + " floors=" + run.ScheduleFor(state).FloorCount : " schedule=legacy"));
        return null;
    }

    // Build Deck: why the built list may not start a run of row classId with the active profile's collection (copies per live
    // copy group, never more than owned), or null. An unknown row is left to DungeonRun.NewRun's own refusal.
    private static string BuiltListRefusal(DungeonRun run, string classId, IReadOnlyList<string> builtCards)
    {
        var cls = run.Data.FindClass(classId);
        if (cls == null) return null;
        var collection = LocalLadder.Profile;
        if (collection == null) return NativeDungeonRunText.NoSaveCaption;
        var reasons = DungeonRunBuild.DeckReasons(builtCards, cls.ClassSet, run.Rules.StarterSize,
            id => collection.TotalOwnedCount(ClientCardId(id)),
            id => id == null ? null : LocalCardCatalog.CopyGroup(ClientCardId(id)),
            SabberStoneCore.Model.OfflinePoolPolicy.Load());
        return reasons.Count == 0 ? null : DungeonRun.IllegalBuiltList + string.Join(", ", reasons) + ".";
    }

    /// <summary>A random run seed (never 0). Only random-seed runs feed stats and unlocks.</summary>
    internal static long RandomSeed()
    {
        long seed = BitConverter.ToInt64(Guid.NewGuid().ToByteArray(), 0) & long.MaxValue;
        return seed == 0 ? 1 : seed;
    }

    // ------------------------------------------------------------------ in-match names and text

    /// <summary>Starts showing run names for a staged run match; <see cref="EndMatch"/> stops it.</summary>
    internal static void BeginMatch(DungeonRunState state)
    {
        var run = Rules ?? throw new InvalidOperationException("Dungeon Run is disabled.");
        var cls = run.RunClass(state);
        var boss = run.CurrentBoss(state);
        var names = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [cls.HeroCard] = cls.Name,
            [boss.HeroCard] = boss.Name,
        };
        // Phase 8: a phased boss keeps its name through its forms (their hero cards are other client cards).
        foreach (var form in boss.Forms.Where(f => f.Hero != null)) names[form.Hero] = boss.Name;
        lock (Gate) matchNames = names;
    }

    internal static void EndMatch() { lock (Gate) matchNames = null; }

    /// <summary>
    /// Records the active run's fight outcome and commits the sidecar (design R10). Called once per fight, BEFORE the
    /// flagged Pending is dropped: a crash in between leaves a Pending that boot recovery drops, never a lost outcome.
    /// Always ends the in-match name overrides. Returns the run state after the outcome.
    /// </summary>
    /// <param name="result">What the match asked the run to keep (phase 6, NativeMatch.DungeonRunResult); applied on a win only.</param>
    /// <param name="end">Phase 8: what the fight left (NativeMatch.DungeonRunEnd: boss Health and form, hero damage, heroes used).</param>
    internal static DungeonRunState RecordFightOutcome(DungeonRunOutcome outcome, RunMatchResult result = null, RunMatchEnd end = null)
    {
        var run = Rules ?? throw new InvalidOperationException("Dungeon Run is disabled.");
        var loaded = Save ?? throw new InvalidOperationException("No profile is open.");
        var current = loaded.Active ?? throw new InvalidOperationException("No active run.");
        if (current.Phase != DungeonRunPhase.InMatch) throw new InvalidOperationException("The run is not in a fight.");
        // Memory must never run ahead of the file: if the change or its commit fails, the save goes back to the snapshot
        // (still InMatch, as on disk), so a retry or the stale-fight restage sees exactly what a restart would.
        var snapshot = DungeonRunStore.Clone(loaded);
        List<string> notes;
        try
        {
            notes = run.RecordOutcome(current, loaded.Profile, outcome, result, end);
            Commit();
        }
        catch
        {
            // Step 9 (D6): the version is rolled back too, through the store's helper, as Mutate does.
            lock (Gate) DungeonRunStore.Restore(loaded, snapshot);
            throw;
        }
        EndMatch();
        foreach (string note in notes) Log?.Invoke("Dungeon Run match result: " + note);
        Log?.Invoke("Dungeon Run fight recorded: floor " + current.Floor + " " + outcome + " -> " + current.Phase
            + (current.IsActRun ? " (node " + current.Node + ", deck " + current.Deck.Count + ", majors " + current.MajorsCleared + ")" : ""));
        return current;
    }

    // One-shot: the next finished-match route goes to the hub (and reopens the run screen) instead of the deck picker.
    private static bool returnToRunHub;
    internal static void RequestReturnToRunHub() { lock (Gate) returnToRunHub = true; }
    internal static bool TakeReturnToRunHub() { lock (Gate) { bool value = returnToRunHub; returnToRunHub = false; return value; } }
    /// <summary>Raised on the main thread after a run fight is closed and the board can be left; the run screen reopens on it.</summary>
    internal static event Action FightClosed;
    internal static void RaiseFightClosed() { try { FightClosed?.Invoke(); } catch (Exception error) { Log?.Invoke("Dungeon Run screen reopen failed: " + error.Message); } }

    internal static bool InRunMatch { get { lock (Gate) return matchNames != null; } }

    internal static bool TryName(string cardId, out string name)
    {
        name = null;
        if (cardId == null) return false;
        lock (Gate)
        {
            // Only during a run match or an open native picker: shells and portraits keep their client names everywhere else.
            if (matchNames == null) return TryPicker(cardId, card => card.Name, out name);
            if (matchNames.TryGetValue(cardId, out name)) return true;
        }
        name = DungeonRunContent.ForShell(cardId)?.Name;
        return name != null;
    }

    internal static bool TryText(string cardId, out string text)
    {
        text = null;
        if (cardId == null) return false;
        if (!InRunMatch) return TryPicker(cardId, card => card.Text, out text);
        text = DungeonRunContent.ForShell(cardId)?.Text;
        return text != null;
    }

    // ------------------------------------------------------------------ native picker overrides

    /// <summary>What the native picker shows for one client card it borrows (a power, a deck's shell card).</summary>
    internal sealed class PickerCard
    {
        internal string Name, Text;
        internal int? Cost;
    }

    // Replaced whole, never mutated: readers (EntityBase.GetTag runs constantly) take the reference without the lock.
    private static volatile Dictionary<string, PickerCard> pickerCards;

    /// <summary>NativeDungeonRunPicker: from now until <see cref="EndPicker"/>, exactly these client card ids answer with
    /// the run's name, text and cost (outside a run match only).</summary>
    internal static void BeginPicker(IDictionary<string, PickerCard> cards) =>
        pickerCards = cards == null ? null : new Dictionary<string, PickerCard>(cards, StringComparer.Ordinal);

    internal static void EndPicker() => pickerCards = null;

    internal static bool PickerOpen => pickerCards != null;

    private static bool TryPicker(string cardId, Func<PickerCard, string> read, out string value)
    {
        value = null;
        var cards = pickerCards;
        if (cards == null || cardId == null || !cards.TryGetValue(cardId, out PickerCard card)) return false;
        value = read(card);
        return value != null;
    }

    /// <summary>The run cost of a picker power card (NativeUIProbe's EntityDef GetTag(COST) hook).</summary>
    internal static bool TryPickerCost(string cardId, out int cost)
    {
        cost = 0;
        var cards = pickerCards;
        if (cards == null || cardId == null || !cards.TryGetValue(cardId, out PickerCard card) || card.Cost == null) return false;
        cost = card.Cost.Value;
        return true;
    }
}
